#!/usr/bin/env python3
"""旅行手帐 v2 — 把每一页拼贴渲染成图片，并生成 3D 翻页书的数据。

用法（在 source 文件夹里）:
    py render.py            渲染全部
    py render.py s02 s03    只渲染这几页（更快）

改文字   → config.json
换照片   → 把新照片放进 photos/，在 config.json 的 "photos" 里改文件名
改拼贴   → layouts/collage.py（每个跨页一个函数，每一行一个图层）
改样式   → layouts/shared.css
改完重新运行本脚本；cache/ 里的旧碎片可以随时删掉，会自动重建。
"""
from __future__ import annotations

import http.server, json, socketserver, sys, threading, time
from pathlib import Path
from PIL import Image

SRC = Path(__file__).resolve().parent
SITE = SRC.parent
PAGES = SITE / "assets" / "pages"
HTML_DIR = SRC / "html"
sys.path.insert(0, str(SRC / "layouts"))
sys.path.insert(0, str(SRC / "tools"))

CFG = json.loads((SRC / "config.json").read_text(encoding="utf-8"))
import kit as K  # noqa: E402
K.CFG = CFG
import collage  # noqa: E402

PW, PH = int(CFG["pageWidth"]), int(CFG["pageHeight"])
SW, SH = PW * 2, PH
# CSS layout stays PW x PH; Playwright screenshots at this device scale.
DSF = 2
OUT_W, OUT_H = PW * DSF, PH * DSF
PORT = 4179


def doc(left, right):
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<link rel="stylesheet" href="../layouts/shared.css"></head>
<body><div class="spread">{left}{right}</div></body></html>"""


def start_server():
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *a, **k):
            super().__init__(*a, directory=str(SRC), **k)

        def log_message(self, *a):
            pass

    socketserver.ThreadingTCPServer.allow_reuse_address = True
    httpd = socketserver.ThreadingTCPServer(("127.0.0.1", PORT), Quiet)
    httpd.daemon_threads = True
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd


def render(only=None):
    from playwright.sync_api import sync_playwright
    HTML_DIR.mkdir(exist_ok=True)
    PAGES.mkdir(parents=True, exist_ok=True)
    todo = [(sid, fn) for sid, fn in collage.SPREADS if not only or sid in only]
    for sid, fn in todo:
        left, right = fn()
        (HTML_DIR / f"{sid}.html").write_text(doc(left, right), encoding="utf-8")
        print(f"  html {sid}")
    httpd = start_server()
    try:
        with sync_playwright() as p:
            try:
                browser = p.chromium.launch(channel="chrome", headless=True, args=["--no-sandbox"])
            except Exception:
                browser = p.chromium.launch(headless=True, args=["--no-sandbox"])
            page = browser.new_page(viewport={"width": SW, "height": SH}, device_scale_factor=DSF)
            for sid, _ in todo:
                page.goto(f"http://127.0.0.1:{PORT}/html/{sid}.html", wait_until="networkidle", timeout=90000)
                page.evaluate("() => document.fonts.ready")
                bad = page.evaluate("() => [...document.images].filter(i => !(i.complete && i.naturalWidth > 0)).map(i => i.src)")
                if bad:
                    print("  ! missing images:", bad)
                time.sleep(0.2)
                raw = HTML_DIR / f"{sid}_full.png"
                page.screenshot(path=str(raw), type="png")
                im = Image.open(raw).convert("RGB")
                tw, th = SW * DSF, SH * DSF
                if im.size != (tw, th):
                    raise RuntimeError(f"{sid} screenshot was {im.size}, expected {(tw, th)}")
                jpeg = dict(quality=92, subsampling=0, optimize=True)
                im.crop((0, 0, OUT_W, OUT_H)).save(PAGES / f"{sid}-left.jpg", **jpeg)
                im.crop((OUT_W, 0, tw, th)).save(PAGES / f"{sid}-right.jpg", **jpeg)
                if "--keep-full" not in sys.argv:
                    raw.unlink()  # 整张预览图很大，默认删掉
                print(f"  rendered {sid}")
            browser.close()
    finally:
        httpd.shutdown()


def write_book_data():
    ids = [sid for sid, _ in collage.SPREADS]
    alts = getattr(collage, "ALTS", {})
    inter = [s for s in ids if s != "cover"]
    rows = []
    for sid in inter:
        a = alts.get(sid, ("", ""))
        rows.append(f'    {{ id: "{sid}", left: {{ file: "{sid}-left.jpg", alt: {json.dumps(a[0], ensure_ascii=False)} }}, '
                    f'right: {{ file: "{sid}-right.jpg", alt: {json.dumps(a[1], ensure_ascii=False)} }} }}')
    ca = alts.get("cover", ("", ""))
    js = f"""// Generated by source/render.py — edit config.json / layouts/collage.py and re-render.
window.PHOTOBOOK = {{
  id: "travel-journal-2026-v3-hd",
  title: {json.dumps(CFG["title"])},
  pageWidth: {OUT_W},
  pageHeight: {OUT_H},
  frontCover: {{ file: "cover-right.jpg", alt: {json.dumps(ca[1], ensure_ascii=False)} }},
  spreads: [
{",\n".join(rows)}
  ],
  backCover: {{ file: "cover-left.jpg", alt: {json.dumps(ca[0], ensure_ascii=False)} }}
}};
"""
    (SITE / "book-data.js").write_text(js, encoding="utf-8")
    print("  wrote book-data.js")


if __name__ == "__main__":
    only = {a for a in sys.argv[1:] if not a.startswith("--")} or None
    render(only)
    if not only:
        write_book_data()
    print("Done.  Open the book: double-click start.bat, then http://127.0.0.1:4173/")
